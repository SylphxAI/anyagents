CREATE OR REPLACE FUNCTION public.revoke_remote_session_tokens_on_stop() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.state IN ('paused', 'archived') THEN
        UPDATE public.remote_session_tokens
        SET revoked_at_ms = (EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::BIGINT
        WHERE agent_id = NEW.id AND revoked_at_ms IS NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS remote_session_tokens_revoke_on_stop ON public.agents;
CREATE TRIGGER remote_session_tokens_revoke_on_stop
AFTER UPDATE OF state ON public.agents
FOR EACH ROW
EXECUTE FUNCTION public.revoke_remote_session_tokens_on_stop();

