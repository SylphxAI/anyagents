//! Thin configuration boundary for the external `spiron` CLI.
//!
//! AnyAgents owns mailbox/control-plane state; Spiron owns model turns,
//! context windows, tools and memory.  This module only writes the MCP mount
//! consumed by the external process and keeps legacy Sylphx model defaults.

use std::path::Path;

use anyagents_core::Error;

/// The default model retained for existing `sylphx` agent records.
pub const DEFAULT_SPIRON_MODEL: &str = "sylphx/openai/gpt-6.1-sol#medium";
/// Compatibility value used by the managed-worktree marker consumed by Spiron.
pub const CLOUD_WORKSPACE_DIR: &str = "/home/user";

/// Write the narrow JSON mount passed to Spiron with `--mcp-config`.
///
/// The executable and arguments are generated by AnyAgents itself, while the
/// external CLI remains responsible for opening and using the MCP connection.
pub fn write_spiron_config(
    config_dir: &Path,
    model: Option<&str>,
    mcp_command: &Path,
    mcp_args: &[String],
) -> Result<(), Error> {
    let _ = model; // The CLI receives the exact configured model as --model.
    let value = serde_json::json!({
        "mcpServers": {
            "anyagents": {
                "command": mcp_command.display().to_string(),
                "args": mcp_args,
                "env": {},
            }
        }
    });
    let path = config_dir.join("spiron-mcp.json");
    let bytes = serde_json::to_vec_pretty(&value).map_err(|err| Error::Message(err.to_string()))?;
    std::fs::write(path, bytes)?;
    Ok(())
}
